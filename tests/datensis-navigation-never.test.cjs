'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const twig=fs.readFileSync('templates/vault/index.html.twig','utf8');
const web=fs.readFileSync('public/assets/vault.js','utf8');
const popup=fs.readFileSync('chrome-extension/popup.js','utf8');
const popupHTML=fs.readFileSync('chrome-extension/popup.html','utf8');
const popupCSS=fs.readFileSync('chrome-extension/popup.css','utf8');
assert.match(twig,/data-view="vault"[^>]+>[\s\S]*?Mon coffre<\/span>/);
for(const s of ['PILOTAGE CABINET','FILTRES DU COFFRE','Aucun dossier','id="folders-nav"']) assert(!twig.includes(s),s+' should be removed from the UI');
assert(twig.includes('id="vault-filter"'));
for(const f of ['all','favorite','login','card','identity','note'])assert(twig.includes(`<option value="${f}">`), 'missing filter '+f);
const filterMarkup=twig.match(/<select id="vault-filter"[^>]*>([\s\S]*?)<\/select>/)?.[1]||'';
assert(!filterMarkup.includes('<option value="ssh">'), 'SSH should not be in quick filter');
assert(filterMarkup.includes('<option value="trash">'), 'trash must be accessible for deleted passwords');
assert(web.includes("$('vault-filter').onchange"));
assert(web.includes("$('section-title').textContent='Mon coffre'"));
assert(twig.includes('<option value="0" selected>Jamais (par défaut)</option>'));
assert(popupHTML.includes('<option value="0" selected>Jamais (par défaut)</option>'));
assert(web.includes('lockMinutes>0&&Date.now()-state.lastActive>=lockMinutes*60000'));
assert(web.includes("localStorage.getItem('ml2c-lock-minutes')===null?0:"));
assert(popup.includes('IDLE_OPTIONS = [0,1,3,5,10,15]'));
assert(popup.includes('if (!state.key || idleMinutes===0) return false;'));
assert(popup.includes('idleMinutes===0){disarmInactivityWatchdog();'));
assert(popup.includes("window.addEventListener('pagehide',()=>lock())"));
assert(popupCSS.includes('.send-mode label:has(input:checked)'));
assert(fs.existsSync('public/assets/datensis-identity.css'));
const brandCss=fs.readFileSync('public/assets/datensis-palette.css','utf8');
for(const hex of ['#FFFFFF','#E96148','#82C4A8','#00778B']) assert(brandCss.includes(hex), 'missing official brand color '+hex);
assert(fs.readFileSync('templates/base.html.twig','utf8').includes('datensis-palette.css'));
assert(web.includes("['all','favorite','login','card','identity','note','trash'].includes(state.filter)"));
console.log('OK: filtre simplifie, palette officielle, Jamais sur site/panneau, Send responsive');
