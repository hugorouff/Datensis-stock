const fs=require('node:fs');const path=require('node:path');const assert=require('node:assert/strict');
const root=path.join(__dirname,'..');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'chrome-extension/manifest.json'),'utf8'));
const html=fs.readFileSync(path.join(root,'chrome-extension/popup.html'),'utf8');
const client=fs.readFileSync(path.join(root,'chrome-extension/popup.js'),'utf8');
const vaultTemplate=fs.readFileSync(path.join(root,'templates/vault/index.html.twig'),'utf8');
const api=fs.readFileSync(path.join(root,'src/Controller/ExtensionApiController.php'),'utf8');
const security=fs.readFileSync(path.join(root,'config/packages/security.yaml'),'utf8');
const responseSecurity=fs.readFileSync(path.join(root,'src/EventSubscriber/SecureResponseSubscriber.php'),'utf8');
const migration=fs.readFileSync(path.join(root,'migrations/Version20261028000400.php'),'utf8');
const kdfMigration=fs.readFileSync(path.join(root,'migrations/Version20261103000100.php'),'utf8');
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(x=>x[1]);
for(const match of client.matchAll(/\$\('([a-zA-Z0-9-]+)'\)/g))assert.ok(ids.includes(match[1]),`ID manquant : ${match[1]}`);
assert.equal(new Set(ids).size,ids.length,'IDs dupliques');
assert.equal(manifest.manifest_version,3);
assert.deepEqual(manifest.permissions,['storage','activeTab','sidePanel','alarms','scripting','privacy']);
assert.ok(manifest.host_permissions.includes('https://*/*'));
assert.equal(manifest.action.default_popup,undefined);
assert.equal(manifest.background.service_worker,'service-worker.js');
const worker=fs.readFileSync(path.join(root,'chrome-extension/service-worker.js'),'utf8');
assert.ok(worker.includes('chrome.sidePanel.setPanelBehavior'));
assert.ok(!worker.includes('chrome.windows.create'));
assert.equal(manifest.side_panel.default_path,'popup.html');
assert.ok(worker.includes('openPanelOnActionClick:true'));
assert.ok(!client.includes('if(document.hidden)lock()'), 'Un changement d onglet ne doit pas verrouiller immediatement');
for(const removed of ['entry-client','entry-owner'])assert.ok(!ids.includes(removed),removed+' doit etre masque');
assert.ok(ids.includes('entry-folder'),'Le choix du dossier doit etre disponible');
assert.ok(ids.includes('entry-folder-new'),'La creation de sous-dossiers doit etre disponible');
assert.ok(html.includes('data-fields="note" hidden'));
assert.ok(html.includes('entry-notes'));
assert.ok(client.includes('Contenu de la note sécurisée'));
assert.ok(!manifest.permissions.includes('cookies'));
assert.ok(manifest.permissions.includes('scripting'));
assert.ok(ids.includes('entry-url'));
assert.ok(ids.includes('fill-site'));
assert.ok(manifest.content_scripts.some(x=>x.matches.includes('http://127.0.0.1/*')));
assert.ok(client.includes('credentials:\'omit\''));
assert.ok(client.includes('600000'));
assert.ok(client.includes('memorySize:65536'));
assert.ok(client.includes('iterations:3'));
assert.ok(client.includes('kdfVersion'));
assert.ok(client.includes('ensureArgon2()'));
assert.ok(client.includes('source.searchParams.set(\'retry\',\'1\')'));
assert.ok(security.includes('algorithm: argon2id'));
assert.ok(security.includes('migrate_from:'));
assert.ok(kdfMigration.includes('vault_kdf_version'));
assert.ok(responseSecurity.includes("'wasm-unsafe-eval'"));
assert.ok(html.includes('hash-wasm-argon2id-4.12.0.min.js'));
assert.match(vaultTemplate,/<script src="\{\{ asset\('assets\/hash-wasm-argon2id-4\.12\.0\.min\.js'\) \}\}\?v=4\.12\.0"><\/script>/);
assert.ok(fs.existsSync(path.join(root,'chrome-extension/hash-wasm-argon2id-4.12.0.min.js')));
assert.ok(!client.includes('storage.local.set({password'));
assert.ok(!client.includes("chrome.tabs.create({url:state.origin+'/api/extension"));
assert.ok(api.includes("if ($this->twoFactorEnabled) return null"));
assert.ok(api.includes("hash('sha256', $token)"));
assert.ok(api.includes("passwordHasher")===false); // injection utilise $hasher
assert.ok(api.includes('isPasswordValid'));
assert.ok(api.includes('expires_at > :now'));
assert.ok(security.includes('^/api/extension/'));
assert.ok(migration.includes('vault_extension_session'));
console.log('Extension mini-coffre : structure, routes, permissions, etats et chiffrement OK');
