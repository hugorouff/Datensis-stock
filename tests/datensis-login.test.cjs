"use strict";
const assert=require('node:assert/strict');
const fs=require('node:fs');
const read=p=>fs.readFileSync(p,'utf8');
const login=read('public/assets/login-unified.js');
const vault=read('public/assets/vault.js');
const tpl=read('templates/vault/index.html.twig');
const popup=read('chrome-extension/popup.js');
const manifest=JSON.parse(read('chrome-extension/manifest.json'));
assert.match(login,/master=form\.elements\['_password'\]\.value/);
assert.match(login,/window\.__vaultBootstrapPassword=master/);
assert.match(login,/loadScript\('\/assets\/vault\.js'\)/);
assert.match(vault,/await unlockWith\(loginPassword\)/);
assert.match(vault,/const key=await vaultKey\(pass,salt\)/);
assert.match(vault,/await decrypt\(state\.initial\.check,key\)/);
assert.match(vault,/document\.addEventListener\('visibilitychange'/);
assert.doesNotMatch(tpl,/class="new-chip"/);
assert.doesNotMatch(read('public/assets/modern.css'),/\.new-chip\{/);
assert.match(read('templates/auth/login.html.twig'),/Se connecter et déverrouiller/);
assert.match(read('templates/base.html.twig'),/Datensis Stock/);
assert.equal(manifest.name,'Datensis Stock | Mini-coffre');
assert.match(popup,/if\(await chrome\.permissions\.contains/);
assert.match(popup,/Le serveur a répondu HTTP/);
assert.equal((popup.match(/window\.addEventListener\('pagehide',\(\)=>lock\(\)\)/g)||[]).length,1);
console.log('OK: connexion web à mot de passe unique, garde de session, popup et suppression des chips');
