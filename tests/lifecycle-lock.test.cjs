'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const src=fs.readFileSync('public/assets/vault-session-guard.js','utf8');
const doc={hidden:false},win={};
vm.runInNewContext(src,{window:win,document:doc});
const g=win.ML2CVaultGuard;
assert.ok(g);const first=g.ticket();
assert.equal(g.active(first),true);
doc.hidden=true;assert.equal(g.active(first),false,'hidden tab cannot unlock');
g.invalidate();doc.hidden=false;assert.equal(g.active(first),false,'old derivation must be cancelled');
const second=g.ticket();assert.equal(g.active(second),true,'fresh unlock can start');
g.depart();assert.equal(g.active(second),false,'pagehide must cancel');
g.restore();assert.equal(g.active(second),false,'BFCache return must remain locked');
assert.equal(g.active(g.ticket()),true,'fresh password entry allowed after return');
const vault=fs.readFileSync('public/assets/vault.js','utf8');
assert.ok(vault.includes("document.addEventListener('visibilitychange'"));
assert.ok(vault.includes("window.addEventListener('pagehide'"));
assert.ok(vault.includes("window.addEventListener('pageshow'"));
assert.ok(vault.includes('assertActive(ticket)'));
assert.ok(vault.includes('bootPassword=null;'));
const login=fs.readFileSync('public/assets/login-unified.js','utf8');
assert.ok(login.includes('cancelBootstrap'));
assert.ok(login.includes('openVault(ticket)'));
const popup=fs.readFileSync('chrome-extension/popup.js','utf8');
assert.ok(popup.includes("window.addEventListener('pagehide',()=>lock())"));
console.log('OK: initial login, hidden-tab cancellation, pagehide, BFCache and popup locking');
